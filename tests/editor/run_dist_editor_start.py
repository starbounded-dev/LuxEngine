#!/usr/bin/env python3
"""The Dist editor starts whatever project an editor opened last, and compiles material graphs.

docs/SHADER_PACK_PLAN.md Phases 1 and 4. Two launches of the Dist editor, each on an isolated user
folder with LUX_STARTUP_SELFTEST (PASS after 30 frames):
  1. No project, after a project's graphs rewrote Resources/Cache/Shader/Generated/MaterialGraphs.glslh
     the way a Debug/Release editor does: the engine pack must not care.
  2. A throw-away project holding the sample's graph material MS_Graph.lmat: the Dist editor must compile
     the graph into the surface shaders ("Material graphs: 1 compiled"), which needs its shader compiler.
The include is put back afterwards.
"""
import os
from pathlib import Path
import shutil
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]
EDITOR = ROOT / "bin/Dist-windows-x86_64/Editor/Editor.exe"
INCLUDE = ROOT / "Editor/Resources/Cache/Shader/Generated/MaterialGraphs.glslh"
GRAPH_MATERIAL = ROOT / "Editor/LuxSampleProject/Assets/Materials/Showcase/MS_Graph.lmat"
PROJECT_INCLUDE = ("// Generated by MaterialGraphRegistry for the open project. Do not edit: it is rewritten\n"
                   "// whenever a material graph changes.\n#define LUX_MATERIAL_GRAPH_COUNT 1\n\n"
                   "void LuxMaterialGraph1(in LuxGraphInput IN, inout LuxGraphOutput OUT)\n{\n}\n\n"
                   "void LuxEvaluateMaterialGraph(uint graphIndex, in LuxGraphInput IN, inout LuxGraphOutput OUT)\n{\n"
                   "\tswitch (graphIndex)\n\t{\n\t\tcase 1u: LuxMaterialGraph1(IN, OUT); break;\n\t\tdefault: break;\n\t}\n}\n")


def launch(root, project=None):
    """Starts the Dist editor; returns (passed, the session's engine log text)."""
    user = root / "user"
    user.mkdir(parents=True)
    startup = f"  StartupProject: {project.as_posix()}\n" if project else ""
    (user / "UserPreferences.yaml").write_text(f"UserPrefs:\n  ShowSplashScreen: false\n{startup}  RecentProjects: []\n")
    status = root / "startup.status"
    env = dict(os.environ, LUX_USER_DATA_DIR=str(user), LUX_STARTUP_SELFTEST=str(status), LUX_NO_WATCHDOG="1")
    result = subprocess.run([str(EDITOR)], cwd=ROOT / "Editor", env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=300)
    logs = "".join(log.read_text(encoding="utf-8", errors="replace") for log in (user / "logs").glob("*.log")) if (user / "logs").is_dir() else ""
    refused = [line for line in logs.splitlines() if "Verify Failed" in line]
    passed = result.returncode == 0 and status.is_file() and status.read_text() == "PASS\n" and not refused
    if not passed:
        detail = refused[0] if refused else f"exit {result.returncode}, status {'present' if status.is_file() else 'missing'}"
        raise SystemExit(f"FAIL: the Dist editor did not start: {detail}; logs: {user / 'logs'}")
    return logs


def main():
    if not EDITOR.is_file():
        raise SystemExit(f"FAIL: build the Dist editor first ({EDITOR})")
    output = ROOT / "bin/dist-editor-start" / str(time.time_ns())

    saved = INCLUDE.read_bytes() if INCLUDE.is_file() else None
    INCLUDE.parent.mkdir(parents=True, exist_ok=True)
    INCLUDE.write_text(PROJECT_INCLUDE, newline="\n")
    try:
        launch(output / "after-other-project")
    finally:
        if saved is None:
            INCLUDE.unlink(missing_ok=True)
        else:
            INCLUDE.write_bytes(saved)
    print("PASS: the Dist editor starts after another project's graphs changed the material-graph include", flush=True)

    project = output / "graph-project"
    (project / "Assets/Materials").mkdir(parents=True)
    shutil.copyfile(GRAPH_MATERIAL, project / "Assets/Materials/MS_Graph.lmat")
    (project / "GraphTest.luxproj").write_text("Project:\n  Name: GraphTest\n  AssetDirectory: Assets\n  AssetRegistry: Assets/AssetRegistry.lzr\n  AutoSave: false\n")
    (project / "Assets/AssetRegistry.lzr").write_text("Assets:\n  - Handle: 17000000000000000008\n    FilePath: Materials/MS_Graph.lmat\n    Type: Material\n")
    saved = INCLUDE.read_bytes() if INCLUDE.is_file() else None
    try:
        logs = launch(output / "graph", project / "GraphTest.luxproj")
    finally:
        if saved is not None:
            INCLUDE.write_bytes(saved)
    if "Material graphs: 1 compiled into the surface shaders" not in logs or "does not compile" in logs:
        raise SystemExit(f"FAIL: the Dist editor did not compile the project's material graph; logs: {output / 'graph/user/logs'}")
    print("PASS: the Dist editor compiles a project's material graph into the surface shaders")
    shutil.rmtree(output, ignore_errors=True)


if __name__ == "__main__":
    main()
