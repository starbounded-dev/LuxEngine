#!/usr/bin/env python3
"""The Dist editor starts on the engine shader pack, whatever project an editor opened last.

Debug/Release editors rewrite Resources/Cache/Shader/Generated/MaterialGraphs.glslh for their open
project; the engine pack must not care (docs/SHADER_PACK_PLAN.md Phase 1). This writes a graph include
like a project would, starts the Dist editor on an isolated user folder with LUX_STARTUP_SELFTEST, and
requires it to get past Renderer::Init. The include is put back afterwards.
"""
import os
from pathlib import Path
import shutil
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]
INCLUDE = ROOT / "Editor/Resources/Cache/Shader/Generated/MaterialGraphs.glslh"
PROJECT_INCLUDE = ("// Generated by MaterialGraphRegistry for the open project. Do not edit: it is rewritten\n"
                   "// whenever a material graph changes.\n#define LUX_MATERIAL_GRAPH_COUNT 1\n\n"
                   "void LuxMaterialGraph1(in LuxGraphInput IN, inout LuxGraphOutput OUT)\n{\n}\n\n"
                   "void LuxEvaluateMaterialGraph(uint graphIndex, in LuxGraphInput IN, inout LuxGraphOutput OUT)\n{\n"
                   "\tswitch (graphIndex)\n\t{\n\t\tcase 1u: LuxMaterialGraph1(IN, OUT); break;\n\t\tdefault: break;\n\t}\n}\n")


def main():
    editor = ROOT / "bin/Dist-windows-x86_64/Editor/Editor.exe"
    if not editor.is_file():
        raise SystemExit(f"FAIL: build the Dist editor first ({editor})")
    output = ROOT / "bin/dist-editor-start" / str(time.time_ns())
    user = output / "user"
    user.mkdir(parents=True)
    (user / "UserPreferences.yaml").write_text("UserPrefs:\n  ShowSplashScreen: false\n  RecentProjects: []\n")
    status = output / "startup.status"

    saved = INCLUDE.read_bytes() if INCLUDE.is_file() else None
    INCLUDE.parent.mkdir(parents=True, exist_ok=True)
    INCLUDE.write_text(PROJECT_INCLUDE, newline="\n")
    try:
        env = dict(os.environ, LUX_USER_DATA_DIR=str(user), LUX_STARTUP_SELFTEST=str(status), LUX_NO_WATCHDOG="1")
        result = subprocess.run([str(editor)], cwd=ROOT / "Editor", env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=180)
    finally:
        if saved is None:
            INCLUDE.unlink(missing_ok=True)
        else:
            INCLUDE.write_bytes(saved)

    logs = "".join(log.read_text(encoding="utf-8", errors="replace") for log in (user / "logs").glob("*.log")) if (user / "logs").is_dir() else ""
    refused = [line for line in logs.splitlines() if "Verify Failed" in line or "Shader pack" in line and "stale" in line]
    if result.returncode or not status.is_file() or status.read_text() != "PASS\n" or refused:
        detail = refused[0] if refused else f"exit {result.returncode}, status {'present' if status.is_file() else 'missing'}"
        raise SystemExit(f"FAIL: the Dist editor did not start on the engine shader pack: {detail}; logs: {user / 'logs'}")
    shutil.rmtree(output, ignore_errors=True)
    print("PASS: the Dist editor starts on the engine shader pack with a project's material graphs in the include")


if __name__ == "__main__":
    main()
