#!/usr/bin/env python3
"""Fails when Editor/Resources/ShaderPack.lsp is older than the shader sources (no GPU, no build).

    python tests/shaders/check_engine_pack.py

Recomputes ShaderPack::ComputeShaderInputIdentity (Core/Source/Lux/Renderer/ShaderPack.cpp) for an
engine pack - every shader source under Editor/Resources/Shaders plus the no-graph material include -
and compares it with the committed stamp. Keep the two in step: a change to either side shows up
here as a mismatch on a freshly built pack.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
EDITOR = ROOT / "Editor"
STAMP = EDITOR / "Resources/ShaderPack.lsp.stamp"
EXTENSIONS = {".glsl", ".glslh", ".hlsl", ".hlslh", ".slh"}
INCLUDE_PATH = "Resources/Cache/Shader/Generated/MaterialGraphs.glslh"
# MaterialGraphRegistry.cpp: s_Header + "#define LUX_MATERIAL_GRAPH_COUNT 0\n" (EmptyInclude).
EMPTY_INCLUDE = ("// Generated by MaterialGraphRegistry for the open project. Do not edit: it is rewritten\n"
                 "// whenever a material graph changes.\n"
                 "#define LUX_MATERIAL_GRAPH_COUNT 0\n")


def fnv(data: bytes) -> int:
    """Hash::GenerateFNVHash: 32-bit FNV-1a over `char` (signed on MSVC and GCC x86), then one more
    multiply - it hashes a trailing NUL."""
    value = 2166136261
    for byte in data + b"\0":
        value ^= (byte - 256 if byte > 127 else byte) & 0xFFFFFFFF
        value = (value * 16777619) & 0xFFFFFFFF
    return value


def identity() -> str:
    inputs = []
    for path in (EDITOR / "Resources/Shaders").rglob("*"):
        if path.is_file() and path.suffix.lower() in EXTENSIONS:
            inputs.append((path.relative_to(EDITOR).as_posix(), str(fnv(path.read_bytes().replace(b"\r", b"")))))
    inputs.append((INCLUDE_PATH, str(fnv(EMPTY_INCLUDE.encode()))))
    chain = "".join(f"{path}:{digest};" for path, digest in sorted(inputs))
    return str(fnv(chain.encode()))


def stamp_field(text: str, key: str) -> str:
    for line in text.splitlines():
        if line.startswith(key + ":"):
            return line.split(":", 1)[1].strip().strip('"')
    return ""


def main() -> int:
    assert fnv(b"") == 0x050C5D1F, "FNV-1a self-check"  # the published FNV-1a of a single NUL byte
    signed = ((2166136261 ^ 0xFFFFFFE2) * 16777619) & 0xFFFFFFFF  # 0xE2 xored as the signed char -30
    assert fnv(b"\xe2") == (signed * 16777619) & 0xFFFFFFFF, "signed-char self-check"
    if not STAMP.is_file():
        print(f"FAIL: {STAMP.relative_to(ROOT)} is missing")
        return 1
    text = STAMP.read_text(encoding="utf-8")
    current, recorded, kind = identity(), stamp_field(text, "ShaderInputs"), stamp_field(text, "Kind")
    if kind != "Engine" or current != recorded:
        print(f"FAIL: the engine shader pack is stale (stamp kind {kind or 'none'}, inputs {recorded}; sources now {current}).")
        print("Rebuild it with a Debug or Release editor, then commit both files (Resources/ShaderPack.lsp and .stamp):")
        print("    python scripts/Update-ShaderPack.py")
        print("  or by hand, from the Editor folder:  ..\\bin\\Release-windows-x86_64\\Editor\\Editor.exe --build-shader-pack")
        return 1
    print(f"PASS: engine shader pack matches the shader sources ({current})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
